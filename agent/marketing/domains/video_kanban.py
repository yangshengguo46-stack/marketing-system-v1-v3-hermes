    def assess_material(
        self,
        *,
        execution_id: str,
        inspection_id: str,
        relevance_score: float,
        semantic_evidence: str,
        observed_subjects: list[str],
        rejection_reasons: list[str] | None = None,
        source_in: float | None = None,
        source_out: float | None = None,
        actor_profile: str | None = None,
        tenant: str | None = None,
        kanban_task_id: str | None = None,
    ) -> dict[str, Any]:
        """Persist the Material Scout's frame-grounded relevance decision."""

        _execution, _workspace, task_id = self._require_dispatched_role(
            execution_id=execution_id,
            expected_profile="marketing-video-material-scout",
            actor_profile=actor_profile,
            tenant=tenant,
            kanban_task_id=kanban_task_id,
        )
        inspection = self.get_material_inspection(str(inspection_id or "").strip())
        if inspection["execution_id"] != execution_id:
            raise ValueError("material inspection belongs to another execution")
        if inspection["model"] != "local_watch_pending":
            return inspection
        score = max(0.0, min(1.0, float(relevance_score)))
        evidence_text = str(semantic_evidence or "").strip()
        subjects = [str(item).strip()[:300] for item in observed_subjects if str(item).strip()]
        if not evidence_text or not subjects:
            raise ValueError("semantic_evidence and observed_subjects are required")
        start = None if source_in is None else max(0.0, float(source_in))
        end = None if source_out is None else float(source_out)
        passed = score >= 0.72
        if passed and (start is None or end is None or end <= start):
            raise ValueError("passing video assessment requires source_in/source_out")
        payload = dict(inspection["evidence"])
        payload.update({
            "status": "passed" if passed else "rejected",
            "semantic_evidence": evidence_text[:2_000],
            "observed_subjects": subjects[:20],
            "rejection_reasons": [
                str(item).strip()[:400]
                for item in (rejection_reasons or [])
                if str(item).strip()
            ][:20],
            "source_in": round(start, 3) if start is not None else None,
            "source_out": round(end, 3) if end is not None else None,
        })
        receipt = dict(inspection["receipt"])
        receipt.update({
            "assessment_owner": "hermes_material_scout",
            "kanban_task_id": task_id,
            "assessed_at": _now(),
            "cost_cny": 0,
            "paid_services": [],
        })
        with self._transaction() as db:
            db.execute(
                """UPDATE marketing_video_material_inspections
                SET model='hermes_material_scout',passed=?,score=?,
                    evidence_json=?,receipt_json=?
                WHERE id=?""",
                (1 if passed else 0, score, _json(payload), _json(receipt), inspection["id"]),
            )
        return self.get_material_inspection(inspection["id"])

