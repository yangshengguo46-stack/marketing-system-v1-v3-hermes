    @staticmethod
    def _locked_input_hashes(workspace: Path) -> dict[str, str]:
        hashes: dict[str, str] = {}
        for relative in LOCKED_WORKSPACE_INPUTS:
            path = workspace / relative
            if not path.is_file():
                raise ValueError(f"locked video input is missing: {relative}")
            hashes[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
        return hashes

    @classmethod
    def _validate_locked_inputs(
        cls, execution: dict[str, Any], workspace: Path
    ) -> None:
        expected = (execution.get("execution") or {}).get("input_integrity")
        if not isinstance(expected, dict) or set(expected) != set(LOCKED_WORKSPACE_INPUTS):
            raise ValueError("locked video input integrity record is missing")
        actual = cls._locked_input_hashes(workspace)
        changed = [
            relative
            for relative in LOCKED_WORKSPACE_INPUTS
            if str(expected.get(relative) or "") != actual[relative]
        ]
        if changed:
            raise ValueError(
                "locked video inputs were modified: " + ", ".join(changed)
            )

