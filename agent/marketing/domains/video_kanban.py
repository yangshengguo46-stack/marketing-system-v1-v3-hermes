def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _redact(value: Any) -> Any:
    if isinstance(value, dict):
        return {
            str(key): "[REDACTED]"
            if str(key).strip().lower() in _SENSITIVE_KEYS
            else _redact(item)
            for key, item in value.items()
        }
    if isinstance(value, list):
        return [_redact(item) for item in value]
    return value


def _model_cost_cny(*, model: str, usage: dict[str, Any]) -> float:
    input_tokens = max(0, int(usage.get("input_tokens") or 0))
    output_tokens = max(0, int(usage.get("output_tokens") or 0))
    cache_read_tokens = max(0, int(usage.get("cache_read_tokens") or 0))
    if model.startswith(DOUBAO_PRO_PREFIX) or model == DOUBAO_PRO_ALIAS:
        input_rate = DOUBAO_PRO_INPUT_CNY_PER_MILLION
        cache_rate = DOUBAO_PRO_CACHE_HIT_CNY_PER_MILLION
        output_rate = DOUBAO_PRO_OUTPUT_CNY_PER_MILLION
    elif model == DOUBAO_LITE_MODEL:
        input_rate = DOUBAO_LITE_INPUT_CNY_PER_MILLION
        cache_rate = DOUBAO_LITE_CACHE_HIT_CNY_PER_MILLION
        output_rate = DOUBAO_LITE_OUTPUT_CNY_PER_MILLION
    elif model == DOUBAO_MINI_MODEL:
        input_rate = DOUBAO_MINI_INPUT_CNY_PER_MILLION
        cache_rate = DOUBAO_MINI_CACHE_HIT_CNY_PER_MILLION
        output_rate = DOUBAO_MINI_OUTPUT_CNY_PER_MILLION
    else:
        raise ValueError(f"unsupported video model pricing: {model}")
    return round(
        (
            input_tokens * input_rate
            + cache_read_tokens * cache_rate
            + output_tokens * output_rate
        )
        / 1_000_000,
        8,
    )


def _record(row: Any) -> dict[str, Any]:
    result = dict(row)
    for field in ("model_json", "budget_json", "execution_json", "receipt_json"):
        result[field.removesuffix("_json")] = json.loads(result.pop(field) or "{}")
    return result


def _slug(value: str, *, fallback: str) -> str:
    import re

    safe = re.sub(r"[^a-z0-9]+", "-", str(value or "").lower()).strip("-")
    return (safe[:42].strip("-") or fallback).strip("-")


def _aspect_for(platform: str, context: dict[str, Any]) -> tuple[str, str]:
    explicit = str(
        context.get("aspect_ratio")
        or (context.get("platform_blueprint") or {}).get("aspect_ratio")
        or ""
    ).strip()
    if explicit in {"9:16", "16:9", "1:1", "3:4", "4:5"}:
        aspect = explicit
    elif platform in {"youtube", "bilibili"}:
        aspect = "16:9"
    else:
        aspect = "9:16"
    resolution = {
        "9:16": "1080x1920",
        "16:9": "1920x1080",
        "1:1": "1080x1080",
        "3:4": "1080x1440",
        "4:5": "1080x1350",
    }[aspect]
    return aspect, resolution


