    def _set_failure(self, execution_id: str, exc: Exception) -> None:
        now = _now()
        with self._transaction() as db:
            db.execute(
                """UPDATE marketing_video_executions
                SET status='blocked',failure_code=?,settled_at=?,updated_at=? WHERE id=?""",
                (f"{type(exc).__name__}: {str(exc)[:400]}", now, now, execution_id),
            )

