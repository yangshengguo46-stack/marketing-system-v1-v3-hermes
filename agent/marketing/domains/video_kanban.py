        narration = str(narration_text or "").strip()
        subject = str(visual_subject or "").strip()
        if not narration or not subject:
            raise ValueError("narration_text and visual_subject are required")
        if len(narration) > 1_500 or len(subject) > 800:
            raise ValueError("material semantic contract is too long")
        strategy = str(composition_strategy or "").strip()
        if strategy and strategy not in {"full_bleed", "inset_card", "letterbox"}:
            raise ValueError("unsupported composition strategy")
        negatives = [
            str(item).strip()[:300]
            for item in (negative_conditions or [])
            if str(item).strip()
        ][:12]
