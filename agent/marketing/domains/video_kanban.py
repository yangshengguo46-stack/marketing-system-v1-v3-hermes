    def reconcile_scope(self, *, user_id: str, account_id: str) -> None:
        """Project terminal official-Kanban state into the Draft Box boundary.

        Kanban remains the only execution owner.  This read-side reconciliation
        only prevents a failed or exhausted official board from being displayed
        forever as ``queued`` in Marketing OS; it never claims, retries, routes,
        unblocks, or completes a Kanban task.
        """

        with self._connection() as db:
            rows = db.execute(
                """SELECT * FROM marketing_video_executions
                WHERE user_id=? AND account_id=?
                  AND status IN ('preparing','queued','blocked')
                  AND (production_id IS NULL OR production_id='')""",
                (user_id, account_id),
            ).fetchall()
        for row in rows:
            execution = _record(row)
            projection = execution.get("execution") or {}
            board = str(projection.get("board") or "").strip() or None
            root_task_id = str(execution.get("root_task_id") or "").strip()
            if not root_task_id:
                continue
            try:
                from hermes_cli import kanban_db as kb

                conn = kb.connect(board=board)
                try:
                    root = kb.get_task(conn, root_task_id)
                    tasks = kb.list_tasks(
                        conn,
                        tenant=str(execution["tenant"]),
                        include_archived=True,
                    )
                finally:
                    conn.close()
            except Exception:
                continue
            if root is None or not tasks:
                continue
            statuses = {str(task.status) for task in tasks}
            # A todo descendant behind a blocked parent is not executable work.
            # Treat only dispatched/runnable states as live; otherwise a failed
            # Editor with a todo Reviewer would be projected as queued forever.
            live = statuses & {"scheduled", "ready", "running", "review"}
            desired = "queued"
            failure_code: str | None = None
            if not live and statuses & {"blocked", "triage"}:
                desired = "blocked"
                failure_code = "official_kanban_blocked"
            elif not live and statuses <= {"done", "archived"}:
                desired = "blocked"
                failure_code = "official_kanban_finished_without_reviewer_settlement"
            if execution["status"] == desired and (
                desired != "blocked" or execution.get("failure_code") == failure_code
            ):
                continue
            now = _now()
            with self._transaction() as db:
                db.execute(
                    """UPDATE marketing_video_executions
                    SET status=?,failure_code=?,settled_at=?,updated_at=?
                    WHERE id=? AND status IN ('preparing','queued','blocked')
                      AND (production_id IS NULL OR production_id='')""",
                    (
                        desired,
                        failure_code,
                        now if desired == "blocked" else None,
                        now,
                        execution["id"],
                    ),
                )

