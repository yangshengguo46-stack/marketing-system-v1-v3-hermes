    @staticmethod
    def _workspace_file(workspace: Path, value: str) -> Path:
        candidate = Path(str(value or "")).expanduser()
        if not candidate.is_absolute():
            candidate = workspace / candidate
        resolved = candidate.resolve()
        if resolved != workspace and workspace not in resolved.parents:
            raise ValueError("video artifact path escaped the execution workspace")
        return resolved

    @classmethod
    def _read_workspace_json(cls, workspace: Path, value: str) -> dict[str, Any]:
        path = cls._workspace_file(workspace, value)
        if not path.is_file():
            raise ValueError(f"required video manifest is missing: {path.name}")
        payload = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(payload, dict):
            raise ValueError(f"video manifest must be an object: {path.name}")
        return payload

    @staticmethod
    def _validate_delivery(
        execution: dict[str, Any], manifests: dict[str, dict[str, Any]]
    ) -> None:
        delivery = manifests["delivery"]
        review = manifests["review"]
        materials = manifests["materials"]
        rights = manifests["rights"]
        if str(delivery.get("execution_id") or "") != execution["id"]:
            raise ValueError("delivery manifest belongs to another execution")
        evidence_refs = [
            str(item) for item in delivery.get("evidence_refs") or [] if str(item)
        ]
        allowed_evidence = {
            str(item)
            for item in (execution.get("execution") or {}).get("evidence_refs") or []
            if str(item)
        }
        if not evidence_refs or not set(evidence_refs).issubset(allowed_evidence):
            raise ValueError(
                "delivery evidence is missing or outside the locked topic brief"
            )
        required_review = (
            "passed",
            "semantic_review_pass",
            "caption_safe_area_pass",
            "audio_sync_pass",
            "composition_pass",
            "rights_pass",
        )
        if any(review.get(key) is not True for key in required_review):
            raise ValueError("final review did not pass every required gate")
        repair_rounds = int(review.get("repair_rounds") or 0)
        if repair_rounds < 0 or repair_rounds > 3:
            raise ValueError("repair rounds exceed the three-round limit")
        paid_calls = delivery.get("paid_material_generation_calls") or []
        if paid_calls:
            raise ValueError("paid material generation is forbidden")

        scenes = delivery.get("scenes")
        if not isinstance(scenes, list) or not scenes:
            raise ValueError("delivery has no scene-level Video IR")
        minimum_shots = int(
            (execution.get("execution") or {}).get("minimum_shots") or 1
        )
        if len(scenes) < minimum_shots:
            raise ValueError(
                f"delivery has {len(scenes)} scenes; locked minimum is {minimum_shots}"
            )
        for scene in scenes:
            if not isinstance(scene, dict):
                raise ValueError("delivery scene must be an object")
            narration = scene.get("narration_segment")
            if not isinstance(narration, dict) or not str(
                narration.get("text") or ""
            ).strip():
                raise ValueError("every scene needs a narration segment")
            claim_evidence_refs = scene.get("claim_evidence_refs")
            if not isinstance(claim_evidence_refs, list):
                raise ValueError("every scene needs a claim_evidence_refs array")
            normalized_claim_refs = {
                str(item).strip() for item in claim_evidence_refs if str(item).strip()
            }
            if not normalized_claim_refs.issubset(allowed_evidence):
                raise ValueError("scene claim evidence is outside the locked topic brief")
            claim_quotes = scene.get("claim_evidence_quotes")
            if not isinstance(claim_quotes, dict):
                raise ValueError("every scene needs a claim_evidence_quotes object")
            if set(str(key) for key in claim_quotes) != normalized_claim_refs:
                raise ValueError("scene evidence quotes must match its evidence refs")
            start = scene.get("start_seconds")
            end = scene.get("end_seconds")
            source_in = scene.get("source_in")
            source_out = scene.get("source_out")
            if not all(isinstance(item, (int, float)) for item in (start, end, source_in, source_out)):
                raise ValueError("every scene needs real timecodes and material in/out points")
            if float(start) < 0 or float(end) <= float(start):
                raise ValueError("scene timeline timecodes are invalid")
            if float(source_in) < 0 or float(source_out) <= float(source_in):
                raise ValueError("scene material in/out points are invalid")
            if scene.get("composition_strategy") not in {
                "full_bleed",
                "inset_card",
                "letterbox",
            }:
                raise ValueError("every scene needs an explicit composition strategy")
            scene_review = scene.get("review")
            if not isinstance(scene_review, dict) or scene_review.get("passed") is not True:
                raise ValueError("every scene needs a passing local review")

        shots = materials.get("shots")
        if not isinstance(shots, list) or not shots:
            raise ValueError("material manifest has no shot-level evidence")
        if len(shots) != len(scenes):
            raise ValueError("material evidence and delivery scenes are not one-to-one")
        selected: list[str] = []
        for shot in shots:
            if not isinstance(shot, dict):
                raise ValueError("material shot evidence must be an object")
            material_kind = str(shot.get("material_kind") or "sourced").strip()
            if material_kind not in {"sourced", "original_renderer"}:
                raise ValueError("material kind must be sourced or original_renderer")
            asset_id = str(shot.get("asset_id") or shot.get("source_id") or "").strip()
            relevance = shot.get("semantic_relevance")
            evidence = shot.get("semantic_evidence")
            if not asset_id or not evidence or not isinstance(relevance, (int, float)):
                raise ValueError("every shot needs selected material and semantic evidence")
            if material_kind == "original_renderer":
                if not asset_id.startswith("original_renderer:"):
                    raise ValueError("original renderer material needs a namespaced asset id")
                if not str(shot.get("render_artifact_path") or "").strip():
                    raise ValueError("original renderer material needs a rendered artifact path")
            elif float(relevance) < 0.72:
                raise ValueError("a selected material is below the semantic relevance gate")
            selected.append(asset_id)
        counts = Counter(selected)
        if len(counts) * 2 < len(shots):
            raise ValueError("fewer than half the shots use independent material")
        if max(counts.values()) > 2:
            raise ValueError("one material is reused more than twice")

        rights_assets = rights.get("assets")
        if not isinstance(rights_assets, list):
            raise ValueError("rights map has no asset records")
        rights_by_id = {
            str(item.get("asset_id") or item.get("source_id") or ""): item
            for item in rights_assets
            if isinstance(item, dict)
        }
        for asset_id in counts:
            item = rights_by_id.get(asset_id) or {}
            if item.get("allowed_for_use") is not True:
                raise ValueError(f"material {asset_id} is not rights-authorized")
            if not str(item.get("license") or "").strip() or not str(
                item.get("source_url") or item.get("source_path") or ""
            ).strip():
                raise ValueError(f"material {asset_id} has incomplete provenance")

        model_receipts = delivery.get("model_receipts")
        tool_receipts = delivery.get("tool_receipts")
        tts_receipts = (delivery.get("narration") or {}).get("receipts")
        material_receipts = materials.get("receipts")
        if not all(
            isinstance(value, list) and value
            for value in (model_receipts, tool_receipts, tts_receipts, material_receipts)
        ):
            raise ValueError("model, tool, TTS and material receipts are all required")
        budget = execution.get("budget") or {}
        pro_model = str((execution.get("model") or {}).get("model") or "")
        lite_model = str(budget.get("execution_model") or "")
        allowed_models = {pro_model, lite_model}
        used_models = [str(item.get("model") or "") for item in model_receipts if isinstance(item, dict)]
        if not used_models or any(item not in allowed_models for item in used_models):
            raise ValueError("video used a model outside the locked Pro/Lite budget")
        for item in model_receipts:
            if (
                not isinstance(item, dict)
                or item.get("provider") != "volcengine_ark"
                or not isinstance(item.get("usage"), dict)
                or not isinstance(item.get("estimated_cost_cny"), (int, float))
                or float(item["estimated_cost_cny"]) < 0
            ):
                raise ValueError("every model call needs usage and a non-negative cost receipt")
        total_model_cost = sum(
            float(item.get("estimated_cost_cny") or 0)
            for item in model_receipts
            if isinstance(item, dict)
        )
        if total_model_cost > float(budget.get("max_total_model_cost_cny") or 20.0):
            raise ValueError("video model cost budget was exceeded")
        if used_models.count(pro_model) > int(budget.get("max_pro_model_calls") or 16):
            raise ValueError("Seed 2.1 Pro call budget was exceeded")
        if used_models.count(lite_model) > int(
            budget.get("max_lite_execution_calls") or 16
        ):
            raise ValueError("Seed 2.0 Lite execution call budget was exceeded")
        narration_text = "".join(
            str((scene.get("narration_segment") or {}).get("text") or "")
            for scene in scenes
        )
        if len(narration_text) > int(budget.get("max_tts_characters") or 6_000):
            raise ValueError("TTS character budget was exceeded")
        for item in tts_receipts:
            if (
                not isinstance(item, dict)
                or not str(item.get("provider_task_id") or item.get("log_id") or "").strip()
                or not isinstance(item.get("characters"), int)
                or int(item["characters"]) < 1
                or not isinstance(item.get("estimated_cost_cny"), (int, float))
                or float(item["estimated_cost_cny"]) < 0
            ):
                raise ValueError("every TTS call needs task, character and cost evidence")
        for item in material_receipts:
            if not isinstance(item, dict) or not str(item.get("provider") or "").strip():
                raise ValueError("every material receipt needs a provider")
            provider = str(item.get("provider") or "")
            expected_status = "rendered" if provider == "official_renderer" else "frozen"
            if item.get("status") != expected_status or float(item.get("cost_cny") or 0) != 0:
                raise ValueError("every material receipt must prove a zero-cost source or render")
            if provider == "official_renderer" and not str(
                item.get("artifact_path") or ""
            ).strip():
                raise ValueError("original renderer receipt needs its artifact path")

    @classmethod
    def _validate_claim_evidence_quotes(
        cls,
        execution: dict[str, Any],
        workspace: Path,
        delivery: dict[str, Any],
    ) -> None:
        context = cls._read_workspace_json(workspace, "marketing-context.json")
        evidence_pack = context.get("evidence_pack")
        if not isinstance(evidence_pack, list):
            raise ValueError("locked marketing context has no evidence pack")
        excerpts = {
            str(item.get("id") or ""): str(item.get("excerpt") or "")
            for item in evidence_pack
            if isinstance(item, dict) and str(item.get("id") or "")
        }
        allowed = {
            str(item)
            for item in (execution.get("execution") or {}).get("evidence_refs") or []
            if str(item)
        }
        for scene in delivery.get("scenes") or []:
            if not isinstance(scene, dict):
                continue
            quotes = scene.get("claim_evidence_quotes") or {}
            for evidence_id, quote_value in quotes.items():
                evidence_id = str(evidence_id)
                quote = str(quote_value or "").strip()
                excerpt = excerpts.get(evidence_id, "")
                if evidence_id not in allowed or len(quote) < 6 or quote not in excerpt:
                    raise ValueError(
                        "scene evidence quote is not an exact excerpt from locked evidence"
                    )

    def _validate_material_inspections(
        self, execution: dict[str, Any], materials: dict[str, Any]
    ) -> None:
        shots = [item for item in materials.get("shots") or [] if isinstance(item, dict)]
        workspace = Path(execution["workspace_path"]).resolve()
        original_shots = [
            item
            for item in shots
            if str(item.get("material_kind") or "sourced") == "original_renderer"
        ]
        for shot in original_shots:
            artifact = self._workspace_file(
                workspace, str(shot.get("render_artifact_path") or "")
            )
            if artifact.suffix.lower() != ".mp4" or not artifact.is_file():
                raise ValueError("original renderer material has no rendered MP4 artifact")
        sourced_shots = [item for item in shots if item not in original_shots]
        inspection_ids = [
            str(item.get("inspection_id") or "").strip() for item in sourced_shots
        ]
        if any(not item for item in inspection_ids):
            raise ValueError("every sourced material shot needs a grounded Scout inspection")
        if not inspection_ids:
            return
        placeholders = ",".join("?" for _ in inspection_ids)
        with self._connection() as db:
            rows = db.execute(
                f"""SELECT * FROM marketing_video_material_inspections
                WHERE execution_id=? AND id IN ({placeholders})""",
                [execution["id"], *inspection_ids],
            ).fetchall()
        by_id = {
            str(row["id"]): self._material_inspection_record(row) for row in rows
        }
        for shot, inspection_id in zip(sourced_shots, inspection_ids, strict=True):
            inspection = by_id.get(inspection_id)
            if inspection is None:
                raise ValueError("material inspection is missing from durable execution state")
            receipt = inspection.get("receipt") or {}
            if (
                inspection["shot_id"] != str(shot.get("shot_id") or "")
                or inspection["passed"] is not True
                or float(inspection["score"]) < 0.72
                or inspection["model"] != "hermes_material_scout"
                or receipt.get("provider") != "local_watch"
                or receipt.get("watch_no_whisper") is not True
                or float(receipt.get("cost_cny") or 0) != 0
            ):
                raise ValueError("material inspection does not satisfy the grounded Scout gate")
            semantic = str(
                (inspection.get("evidence") or {}).get("semantic_evidence") or ""
            ).strip()
            if (
                abs(
                    float(shot.get("semantic_relevance") or 0)
                    - float(inspection["score"])
                )
                > 1e-6
                or str(shot.get("semantic_evidence") or "").strip() != semantic
            ):
                raise ValueError(
                    "material manifest does not match the durable visual inspection"
                )

    @staticmethod
    def _probe_audio(path: Path) -> dict[str, Any]:
        result = subprocess.run(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_entries",
                "stream=codec_type,codec_name,sample_rate,channels",
                "-show_entries",
                "format=duration,size",
                "-of",
                "json",
                str(path),
            ],
            check=False,
            capture_output=True,
            text=True,
            timeout=30,
        )
        if result.returncode != 0:
            raise ValueError("ffprobe could not inspect narration audio")
        payload = json.loads(result.stdout)
        streams = list(payload.get("streams") or [])
        audio = next(
            (item for item in streams if item.get("codec_type") == "audio"), {}
        )
        if not audio:
            raise ValueError("narration artifact has no audio stream")
        format_info = payload.get("format") or {}
        duration = round(float(format_info.get("duration") or 0), 3)
        if duration <= 0:
            raise ValueError("narration audio has no measurable duration")
        return {
            "duration_seconds": duration,
            "size_bytes": int(format_info.get("size") or path.stat().st_size),
            "codec": str(audio.get("codec_name") or ""),
            "sample_rate": int(audio.get("sample_rate") or 0),
            "channels": int(audio.get("channels") or 0),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        }

    @staticmethod
    def _probe_final_video(path: Path) -> dict[str, Any]:
        result = subprocess.run(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_entries",
                "stream=codec_type,codec_name,width,height,r_frame_rate",
                "-show_entries",
                "format=duration,size",
                "-of",
                "json",
                str(path),
            ],
            check=False,
            capture_output=True,
            text=True,
            timeout=30,
        )
        if result.returncode != 0:
            raise ValueError("ffprobe could not inspect the final video")
        payload = json.loads(result.stdout)
        streams = list(payload.get("streams") or [])
        video = next((item for item in streams if item.get("codec_type") == "video"), {})
        if not video:
            raise ValueError("final MP4 has no video stream")
        format_info = payload.get("format") or {}
        return {
            "duration_seconds": round(float(format_info.get("duration") or 0), 3),
            "size_bytes": int(format_info.get("size") or path.stat().st_size),
            "codec": str(video.get("codec_name") or ""),
            "width": int(video.get("width") or 0),
            "height": int(video.get("height") or 0),
            "frame_rate": str(video.get("r_frame_rate") or ""),
            "audio_streams": sum(1 for item in streams if item.get("codec_type") == "audio"),
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        }

