    def purge_test_artifacts(
        self,
        *,
        user_id: str,
        account_id: str,
        confirmed: bool,
    ) -> dict[str, Any]:
        """Purge unfinished official-test files while preserving audit rows.

        Executions, model/TTS cost receipts and failure evidence remain in the
        canonical database. Only unfinished workspaces, execution-owned media
        references, unreferenced temporary assets and the unreferenced legacy
        render cache are removed.
        """

        from agent.marketing.domains.media_assets import MediaAssetRepository

        if confirmed is not True:
            raise ValueError("explicit test-artifact purge confirmation is required")
        root = (self.paths.user_data / "marketing-video-kanban").resolve()
        render_cache = (self.paths.user_data / "marketing-video-renders").resolve()
        with self._connection() as db:
            rows = db.execute(
                """SELECT * FROM marketing_video_executions
                WHERE user_id=? AND account_id=?
                  AND (production_id IS NULL OR production_id='')
                ORDER BY created_at,id""",
                (user_id, account_id),
            ).fetchall()
        executions = [_record(row) for row in rows]
        execution_ids = [str(item["id"]) for item in executions]
        if not execution_ids:
            return {
                "execution_ids": [],
                "workspaces_deleted": 0,
                "temporary_assets": {"deleted": 0, "reclaimed_bytes": 0},
                "render_cache_deleted": False,
            }
        now = _now()
        purged_roots: dict[str, str] = {}
        with self._transaction() as db:
            placeholders = ",".join("?" for _ in execution_ids)
            db.execute(
                f"""DELETE FROM media_asset_references
                WHERE owner_kind='video_execution' AND owner_id IN ({placeholders})""",
                execution_ids,
            )
            for execution in executions:
                receipt = dict(execution.get("receipt") or {})
                old_root = str(execution.get("root_task_id") or "").strip()
                if old_root:
                    purged_roots[str(execution["id"])] = old_root
                receipt["artifact_purge"] = {
                    "purged_at": now,
                    "workspace_deleted": True,
                    "previous_root_task_id": old_root or None,
                    "cost_receipts_preserved": True,
                }
                archived_from = (
                    str(execution.get("archived_from_status") or "").strip()
                    or str(execution.get("status") or "blocked")
                )
                if archived_from == "archived":
                    archived_from = "blocked"
                db.execute(
                    """UPDATE marketing_video_executions
                    SET status='archived',archived_from_status=?,archived_at=COALESCE(archived_at,?),
                        root_task_id=NULL,receipt_json=?,updated_at=? WHERE id=?""",
                    (
                        archived_from,
                        now,
                        _json(_redact(receipt)),
                        now,
                        execution["id"],
                    ),
                )
        workspace_bytes = 0
        workspaces_deleted = 0
        for execution in executions:
            workspace = Path(str(execution.get("workspace_path") or "")).expanduser().resolve()
            if root not in workspace.parents or not workspace.is_dir():
                continue
            workspace_bytes += sum(
                path.stat().st_size
                for path in workspace.rglob("*")
                if path.is_file()
            )
            shutil.rmtree(workspace)
            workspaces_deleted += 1
        temporary = MediaAssetRepository(self.paths).purge_unreferenced_temporary(
            user_id=user_id
        )
        render_bytes = 0
        render_deleted = False
        if render_cache.is_dir() and render_cache == (
            self.paths.user_data / "marketing-video-renders"
        ).resolve():
            render_bytes = sum(
                path.stat().st_size
                for path in render_cache.rglob("*")
                if path.is_file()
            )
            shutil.rmtree(render_cache)
            render_deleted = True
        return {
            "execution_ids": execution_ids,
            "workspaces_deleted": workspaces_deleted,
            "workspace_reclaimed_bytes": workspace_bytes,
            "detached_kanban_roots": purged_roots,
            "temporary_assets": temporary,
            "render_cache_deleted": render_deleted,
            "render_cache_reclaimed_bytes": render_bytes,
            "audit_rows_preserved": len(execution_ids),
        }

    def _official_model_receipts(
        self, execution: dict[str, Any]
    ) -> list[dict[str, Any]]:
        """Read model usage from the official Hermes profile sessions.

        Model receipts are system-owned.  Editors and reviewers may not type
        them into a manifest: the finalizer replaces that field from the
        official profile databases. Local watch/Scout inspections have zero
        model cost and stay in their own durable inspection ledger.
        """

        workspace = str(Path(execution["workspace_path"]).resolve())
        pro_model = str((execution.get("model") or {}).get("model") or "")
        lite_model = str(
            (execution.get("budget") or {}).get("execution_model") or ""
        )
        allowed_models = {pro_model, lite_model}
        receipts: list[dict[str, Any]] = []

        model_contract = execution.get("model") or {}
        probes = (
            (model_contract.get("probe_receipt"), pro_model),
            (model_contract.get("execution_probe_receipt"), lite_model),
        )
        for probe, expected_model in probes:
            if not isinstance(probe, dict) or probe.get("model") != expected_model:
                continue
            usage = probe.get("usage") if isinstance(probe.get("usage"), dict) else {}
            receipts.append(
                _redact(
                    dict(probe)
                    | {
                        "source": "startup_probe",
                        "estimated_cost_cny": _model_cost_cny(
                            model=expected_model, usage=usage
                        ),
                    }
                )
            )

        profiles_root = self.paths.user_data / "profiles"
        for profile in OFFICIAL_VIDEO_PROFILES:
            state_db = profiles_root / profile / "state.db"
            if not state_db.is_file():
                continue
            try:
                db = sqlite3.connect(f"file:{state_db}?mode=ro", uri=True)
                db.row_factory = sqlite3.Row
                columns = {
                    str(row[1]) for row in db.execute("PRAGMA table_info(sessions)")
                }
                required = {
                    "id",
                    "model",
                    "cwd",
                    "input_tokens",
                    "output_tokens",
                    "cache_read_tokens",
                }
                if not required.issubset(columns):
                    db.close()
                    continue
                optional = {
                    "cache_write_tokens": "0",
                    "reasoning_tokens": "0",
                    "api_call_count": "0",
                    "started_at": "NULL",
                    "ended_at": "NULL",
                }
                selected = [
                    name if name in columns else f"{fallback} AS {name}"
                    for name, fallback in optional.items()
                ]
                rows = db.execute(
                    f"""SELECT id,model,input_tokens,output_tokens,cache_read_tokens,
                    {','.join(selected)} FROM sessions
                    WHERE cwd=? AND model IN (?,?) ORDER BY started_at,id""",
                    (workspace, pro_model, lite_model),
                ).fetchall()
                db.close()
            except sqlite3.Error:
                continue
            for row in rows:
                model = str(row["model"] or "")
                expected_model = (
                    pro_model if profile in PRO_REASONING_PROFILES else lite_model
                )
                if model not in allowed_models or model != expected_model:
                    continue
                usage = {
                    "input_tokens": max(0, int(row["input_tokens"] or 0)),
                    "output_tokens": max(0, int(row["output_tokens"] or 0)),
                    "cache_read_tokens": max(
                        0, int(row["cache_read_tokens"] or 0)
                    ),
                    "cache_write_tokens": max(
                        0, int(row["cache_write_tokens"] or 0)
                    ),
                    "reasoning_tokens": max(0, int(row["reasoning_tokens"] or 0)),
                }
                if sum(usage.values()) <= 0:
                    continue
                receipts.append(
                    {
                        "provider": "volcengine_ark",
                        "model": model,
                        "profile": profile,
                        "session_id": str(row["id"]),
                        "source": "hermes_profile_session",
                        "usage": usage,
                        "api_call_count": max(0, int(row["api_call_count"] or 0)),
                        "estimated_cost_cny": _model_cost_cny(
                            model=model, usage=usage
                        ),
                        "started_at": row["started_at"],
                        "ended_at": row["ended_at"],
                    }
                )

        return receipts

    def _replace_manifest_model_receipts(
        self,
        *,
        execution: dict[str, Any],
        workspace: Path,
        delivery_path: str,
        delivery: dict[str, Any],
    ) -> None:
        receipts = self._official_model_receipts(execution)
        pro_model = str((execution.get("model") or {}).get("model") or "")
        lite_model = str(
            (execution.get("budget") or {}).get("execution_model") or ""
        )
        if not any(
            item.get("model") == pro_model
            and item.get("source") == "hermes_profile_session"
            for item in receipts
        ):
            raise ValueError("official Seed 2.1 Pro session receipt is missing")
        if not any(
            item.get("model") == lite_model
            and item.get("source") == "hermes_profile_session"
            for item in receipts
        ):
            raise ValueError("official Seed 2.0 Lite execution receipt is missing")
        delivery["model_receipts"] = receipts
        path = self._workspace_file(workspace, delivery_path)
        path.write_text(
            json.dumps(delivery, ensure_ascii=False, indent=2), encoding="utf-8"
        )

